public class Largesttwonumber {
    public static int largest(int a, int b){
        if(a>b){
            return a;
        }
        else{
            return b;

        }

        }
    
        public static void main(String[] args){
            System.out.println("start");
            int res = largest(19,39);
            System.out.println("largest " +res);
            System.out.println("end");


        }

    
}
